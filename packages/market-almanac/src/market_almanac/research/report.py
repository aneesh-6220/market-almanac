"""Render study results as Markdown tables (every table in the write-up comes from here)."""

from __future__ import annotations

from typing import Any

CONTRAST_LABEL = {
    "P_vs_A": "production-region weather vs price history (P vs A)",
    "P_vs_B": "production-region vs market-local weather (P vs B)",
    "B_vs_A": "market-local weather vs price history (B vs A)",
    "P_vs_placebo_shift": "real vs time-shifted production features",
    "P_vs_placebo_crop": "own-crop vs wrong-crop production features",
}


VARIANT_LABEL = {"lag0": "price lag 0", "lag2": "price lag 2", "rawprecip": "raw precipitation (no QC)"}


def _f(v: Any, digits: int = 3) -> str:
    return "n/a" if v is None else f"{v:.{digits}f}"


def _row(r: dict[str, Any], lead: list[str]) -> str:
    ci = f"{_f(r['ci_low'])} to {_f(r['ci_high'])}"
    cells = [
        *lead,
        str(r["horizon"]),
        str(r["n_months"]),
        f"{r['n_rows']:,}",
        _f(r["loss_ratio"]),
        ci,
        _f(r["p_b_better"]),
        _f(r.get("p_holm")) if "p_holm" in r else "",
        "yes" if r.get("fragile") else "no",
    ]
    return "| " + " | ".join(cells) + " |"


HEAD = "| {lead} | h | Months | Rows | Loss ratio | 95% CI | p (one-sided) | p (Holm) | Fragile |"


def _table(rows: list[dict[str, Any]], lead_names: list[str], lead_fn: Any) -> list[str]:
    out = [HEAD.format(lead=" | ".join(lead_names)), "|" + "---|" * (len(lead_names) + 8)]
    out += [_row(r, lead_fn(r)) for r in rows]
    return out


def render_markdown(res: dict[str, Any]) -> str:
    spec = res["spec"]
    code_name = {(e["country"], e["commodity_code"]): e["commodity_name"] for e in res["experiments"]}
    lines = [
        f"<!-- Generated by market_almanac.research.report from study {res['study_id']} ({res['phase']} phase, "
        f"{res.get('generated_at', '')}). Do not edit by hand: re-run `market-almanac study`. -->",
        "",
        "Loss ratio = mean squared error of the second model / mean squared error of the first; below 1 favours "
        "the second model. 95% CI: moving-block bootstrap over origin months of the ratio of monthly mean losses. "
        "p: one-sided HLN-corrected Diebold-Mariano test that the second model has lower loss, computed on the "
        f"monthly mean loss differential pooled over all series. Primary timing: price release lag "
        f"{spec['primary_lag']} month(s).",
        "",
    ]
    for evidence, title in (("confirmatory", "Confirmatory"), ("exploratory", "Exploratory")):
        prim = [r for r in res["pooled"] if r["evidence_class"] == evidence and r["variant"] == "primary"]
        if not prim:
            continue
        lines += [f"### {title}: pooled over crops, primary timing", ""]
        lines += _table(prim, ["Country", "Contrast"], lambda r: [r["country"], CONTRAST_LABEL[r["contrast"]]])
        lines.append("")
        plc = [r for r in res["pooled"] if r["evidence_class"] == evidence and r["variant"].startswith("placebo")]
        if plc:
            lines += [f"### {title}: falsification checks", ""]
            lines += _table(plc, ["Country", "Check"], lambda r: [r["country"], CONTRAST_LABEL[r["contrast"]]])
            lines.append("")
        sens = [
            r
            for r in res["pooled"]
            if r["evidence_class"] == evidence
            and r["variant"] in ("lag0", "lag2", "rawprecip")
            and r["contrast"] != "B_vs_A"
        ]
        if sens:
            lines += [f"### {title}: sensitivity analyses", ""]
            lines += _table(
                sens,
                ["Country", "Variant", "Contrast"],
                lambda r: [r["country"], VARIANT_LABEL[r["variant"]], r["contrast"].replace("_", " ")],
            )
            lines.append("")
        crops = [r for r in res["per_crop"] if r["evidence_class"] == evidence]
        if crops:
            lines += [f"### {title}: by crop, primary timing", ""]
            lines += _table(
                crops,
                ["Country", "Commodity", "Contrast"],
                lambda r: [
                    r["country"],
                    code_name.get((r["country"], r["commodity_code"]), r["commodity_code"]),
                    r["contrast"].replace("_", " "),
                ],
            )
            lines.append("")
    conf = res["confirmatory"]
    if conf["n_tests"]:
        lines += ["### Confirmatory decisions", ""]
        lines += [
            "| Country | h | Contrast | Loss ratio | p (Holm) | Holm-significant | Both halves | Beats placebo | "
            "Not fragile | Outcome |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for d in conf["decisions"]:
            yn = lambda b: "yes" if b else "no"  # noqa: E731
            lines.append(
                f"| {d['country']} | {d['horizon']} | {d['contrast'].replace('_', ' ')} | {_f(d['loss_ratio'])} | "
                f"{_f(d['p_holm'])} | {yn(d['holm_significant'])} | {yn(d['stable_in_both_halves'])} | "
                f"{yn(d['beats_time_shift_placebo'])} | {yn(d['not_fragile'])} | {d['outcome'].replace('_', ' ')} |"
            )
        lines += ["", f"**Outcome: {conf['outcome']['label'].replace('_', ' ')}.** {conf['outcome']['statement']}", ""]
    exps = res["experiments"]
    lines += [
        "### Experiments",
        "",
        "| Experiment | Country | Commodity | Variant | Evidence | Series |",
        "|---|---|---|---|---|---|",
    ]
    lines += [
        f"| `{e['experiment_id']}` | {e['country']} | {e['commodity_name']} | {e['variant']} | {e['evidence_class']} | "
        f"{e['n_series']} |"
        for e in exps
    ]
    return "\n".join(lines) + "\n"
