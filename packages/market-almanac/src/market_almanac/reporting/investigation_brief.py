"""Research brief for a price-shock investigation, rendered deterministically from the investigation document.

Every number in the brief is read from the document the API serves (and that the JSON export contains), so the
brief can be checked line by line against its source; the tests compare them. No text is generated by a model.
"""

from __future__ import annotations

from typing import Any

from market_almanac.analytics.evidence import STATUS_TEXT, month_name, pct

TABLES = ("signals", "peers", "market", "index")
INFERENCE = {
    "descriptive": "descriptive",
    "associational": "associational",
    "predictive": "predictive",
    "causal": "causal",
}


def _md_escape(s: Any) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(header: list[str], rows: list[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(_md_escape(c) for c in r) + " |" for r in rows]
    return out


def _num(v: Any, digits: int = 2) -> str:
    return "" if v is None else f"{v:,.{digits}f}"


def table_rows(doc: dict[str, Any], table: str) -> list[dict[str, Any]]:
    """Rows of one exportable table (the data behind each figure)."""
    s = doc["subject"]
    if table == "signals":
        return [
            {
                "series_id": s["series_id"],
                "period": r["period"],
                "price": r["price"],
                "currency": s["currency"],
                "unit": s["unit"],
                "mom_change": r["mom_pct"],
                "yoy_change": r["yoy_pct"],
                "robust_z": r["z"],
                "rank_among_earlier": r["percentile"],
                "assessment": r["status"],
                "withheld_reason": r["reason"],
            }
            for r in doc["signals"]
        ]
    if table in ("peers", "market"):
        src = doc["peers"]["rows"] if table == "peers" else doc["breadth"]["rows"]
        return [
            {
                "series_id": r["series_id"],
                "market_name": r["market_name"],
                "admin1_name": r["admin1_name"],
                "commodity_name": r["commodity_name"],
                "unit": r["unit"],
                "price_type": r["price_type"],
                "month_assessed": r["period"],
                "yoy_change": r["yoy_pct"],
                "robust_z": r["z"],
                "unusual_same_direction": r["elevated"],
                "assessment": r["status"],
                "reason": r["reason"],
            }
            for r in src
        ]
    if table == "index":
        return [
            {
                "period": r["period"],
                "own_index": r["own"],
                "peer_median_index": r["peer_median"],
                "peer_q25_index": r["peer_q25"],
                "peer_q75_index": r["peer_q75"],
                "peers_observed": r["peers_observed"],
            }
            for r in doc["peers"]["index"]["rows"]
        ]
    raise ValueError(f"unknown table {table!r}")


def render_markdown(doc: dict[str, Any], link: str | None = None) -> str:
    s, cfg, ev = doc["subject"], doc["config"], doc["evidence"]
    cur, unit = str(s["currency"]), str(s["unit"])
    title = (
        f"Price shock investigation: {s['commodity_name']} ({str(s['price_type']).lower()}, {unit}) in "
        f"{s['market_name']}, {s['country_name']}, {month_name(cfg['event'])}"
    )
    L: list[str] = [f"# {title}", ""]
    L += [
        f"**Market:** {s['market_name']}"
        + (f", {s['admin1_name']}" if s.get("admin1_name") else "")
        + f" ({s['country_name']}, {s['country_iso3']})  ",
        f"**Commodity:** {s['commodity_name']}; {s['price_type']} price in {cur} per {unit} (nominal)  ",
        f"**Period investigated:** {month_name(cfg['window']['start'])} to {month_name(cfg['window']['end'])}; "
        f"month of interest {month_name(cfg['event'])}  ",
        f"**Series:** `{s['series_id']}`, {s['n_observations']} monthly prices, {s['first_period']} to "
        f"{s['last_period']}  ",
        f"**Configuration:** `{doc['config_id']}` (method `{cfg['method_version']}`, price snapshot "
        f"`{cfg['snapshot_id']}`)",
        "",
    ]
    if link:
        q = f"series={s['series_id']}&event={cfg['event']}&start={cfg['window']['start']}&end={cfg['window']['end']}"
        L += [f"Reproduce this investigation: {link.rstrip('/')}/investigate?{q}", ""]
    L += ["## Research question", "", doc["question"], ""]
    L += ["## Summary", "", ev["conclusion"]["text"], "", f"*Inference: {ev['conclusion']['inference']}.*", ""]
    L += _table(
        ["Question", "Finding", "Basis"],
        [[c["label"], c["value"], c["detail"]] for c in ev["assessment"]],
    )
    L += ["", "## Observed facts", ""]
    L += [f"- {x['text']}" for x in ev["observed_facts"]]
    L += ["", "## Quantitative description", ""]
    L += [f"- {x['text']} *({INFERENCE[x['inference']]})*" for x in ev["quantitative"]]

    L += ["", "## Price history in the window", ""]
    L += _table(
        ["Month", f"Price ({cur}/{unit})", "Change on month", "Change on year", "Robust z", "Assessment"],
        [
            [
                r["period"],
                _num(r["price"]),
                pct(r["mom_pct"]) if r["mom_pct"] is not None else "",
                pct(r["yoy_pct"]) if r["yoy_pct"] is not None else "",
                f"{r['z']:+.2f}" if r["z"] is not None else "",
                {"ok": "assessed", "withheld": f"withheld ({r['reason']})", "none": ""}.get(r["status"], r["status"])
                if r["price"] is not None
                else "no observation",
            ]
            for r in doc["signals"]
        ],
    )

    L += ["", "## Comparison with other markets", ""]
    px = doc["peers"]["extent"]
    L += [
        f"Comparable markets: same commodity, unit ({unit}), price type and currency ({cur}) in {s['country_name']}. "
        f"{px['n_peers']} found, {px['n_assessable']} assessable; classification **{px['class']}** ({px['rule']}).",
        "",
    ]
    if doc["peers"]["rows"]:
        L += _table(
            ["Market", "Admin 1", "Month", "12-month change", "Robust z", "Unusual, same direction"],
            [
                [
                    r["market_name"],
                    r["admin1_name"] or "",
                    r["period"] or "",
                    pct(r["yoy_pct"]) if r["yoy_pct"] is not None else "",
                    f"{r['z']:+.2f}" if r["z"] is not None else (r["reason"] or ""),
                    {True: "yes", False: "no"}.get(r["elevated"], ""),
                ]
                for r in doc["peers"]["rows"][:30]
            ],
        )
        if len(doc["peers"]["rows"]) > 30:
            L += ["", f"({len(doc['peers']['rows']) - 30} more in the CSV export.)"]
    br = doc["breadth"]["extent"]
    L += [
        "",
        f"Other foods in the same market and currency: {br['n_peers']} found, {br['n_assessable']} assessable; "
        f"classification **{br['class']}**. Only relative (percentage) changes are compared across different foods.",
    ]

    L += ["", "## Seasonality", ""]
    se = doc["seasonality"]
    if se.get("status") == "ok":
        peak_m = month_name(f"2000-{se['peak_calendar_month']:02d}")[:-5]
        trough_m = month_name(f"2000-{se['trough_calendar_month']:02d}")[:-5]
        verdict = str(se.get("verdict")).replace("_", " ")
        L += [
            f"Seasonal profile from {se['years_used']} pre-episode years: prices typically peak in {peak_m} and are "
            f"lowest in {trough_m} (amplitude {pct(se['seasonal_amplitude'])}). Expected change from "
            f"{se['base_month'][:7]} to {se['peak_month'][:7]}: {pct(se['expected_change_pct'])}; observed: "
            f"{pct(se.get('observed_change_pct'))}. Verdict: {verdict}."
        ]
    else:
        L += [f"No seasonal comparison: {se.get('note') or se.get('status')}."]

    L += ["", "## Contextual evidence", ""]
    wx, mac = doc["context"]["weather"], doc["context"]["macro"]
    if wx.get("status") == "ok":
        if wx.get("production_region"):
            p = wx["production_region"]
            L += [
                f"- Production-region rainfall ({p['crop']}): standardised seasonal anomaly "
                f"{p['season_rain_anomaly_z']:+.1f} as of {month_name(p['period'])}. {p.get('basis') or ''}"
            ]
        if wx.get("market_cell"):
            c = wx["market_cell"]
            mean = f"{c['mean_rain_anomaly_z']:+.1f}" if c.get("mean_rain_anomaly_z") is not None else "n/a"
            L += [f"- Market grid-cell rainfall, 12 months to {month_name(c['window']['end'])}: mean anomaly {mean}."]
        L += [f"- {wx['note']}"]
    else:
        L += ["- Weather: not integrated for this market or crop."]
    if mac.get("cpi"):
        L += [
            f"- Consumer price index ({mac['cpi']['provider'].upper()}): {pct(mac['cpi']['yoy_pct'])} over 12 months; "
            f"commodity change deflated by it: {pct(mac['real_yoy_pct'])}."
        ]
    else:
        L += ["- Consumer price index: not integrated for this country (prices are nominal)."]
    if mac.get("fx"):
        L += [f"- Exchange rate, local currency per US dollar: {pct(mac['fx']['yoy_pct'])} over 12 months."]
    else:
        L += ["- Exchange rate: not integrated for this country."]
    L += ["- Missing context is reported as missing; it is never treated as zero."]

    L += ["", "## Possible mechanisms", ""]
    L += _table(
        ["Mechanism", "Assessment", "What the available data show", "What would be needed"],
        [
            [m["name"], STATUS_TEXT[m["status"]], "; ".join(m["evidence"]), "; ".join(m["needed"])]
            for m in ev["mechanisms"]
        ],
    )
    L += ["", "## Evidence gaps", ""] + [f"- {g}" for g in ev["gaps"]]
    L += ["", "## What this evidence does not establish", ""]
    L += [f"- {x['text']} *({x['inference']})*" for x in ev["unsupported"]]

    L += ["", "## Data quality", ""]
    q = doc["observation_quality"]
    L += [
        f"{q['months_observed']} of {q['months_in_window']} months observed in the window; longest gap "
        f"{q['longest_gap_months']} months."
        + (
            f" {q['records_in_window']} stored records, {q['records_not_used']} not used."
            if q.get("records_in_window") is not None
            else ""
        )
    ]
    if q["flagged_records"]:
        L += [
            "",
            *_table(
                ["Month", f"Price ({cur}/{unit})", "Flags", "Used"],
                [
                    [r["period"], _num(r["price"]), ", ".join(r["flags"]), "yes" if r["used"] else "no"]
                    for r in q["flagged_records"]
                ],
            ),
        ]
    if doc["episode"] and doc["episode"]["flags"]:
        L += ["", "Episode flags: " + ", ".join(f"`{f}`" for f in doc["episode"]["flags"]) + "."]

    L += ["", "## Methodology", "", doc["method"]["text"], ""]
    L += [
        "Eligibility: an unusualness assessment is withheld, with the reason, when the series has fewer than 36 "
        "earlier 12-month changes, they span fewer than 4 calendar years, fewer than half of the 24 months up to the "
        "month were observed, or earlier prices barely varied. 12-month changes compare a month with the same month "
        "a year earlier, so a regular seasonal pattern does not by itself look unusual. Consecutive 12-month changes "
        "overlap: the effective number of independent observations is roughly the number of years.",
        "",
        "Prices are nominal and in local currency; nothing is converted between currencies or deflated unless a "
        "consumer price index is shown above. Comparisons across markets use only series with the same commodity, "
        "unit, price type and currency.",
        "",
    ]
    L += ["## Sources and citation", ""]
    for src in doc.get("sources", []):
        L += [f"- {src['name']} ({src['use']}); licence: {src['licence']}; {src['url']}"]
    L += [
        "",
        f"Market Almanac, price-shock investigation `{doc['config_id']}`, method `{cfg['method_version']}`, "
        f"price snapshot `{cfg['snapshot_id']}`.",
        "",
        "## Reproducible configuration",
        "",
        "```json",
        _json(cfg),
        "```",
        "",
        "Retrieve the same analysis from the API: `GET /api/v1/investigations/"
        f"{s['series_id']}?event={cfg['event']}&start={cfg['window']['start']}&end={cfg['window']['end']}`.",
        "",
    ]
    return "\n".join(L)


def _json(v: Any) -> str:
    import json

    return json.dumps(v, indent=2, sort_keys=True)
